# Editors a game IDE does not need, hidden from the editor-type menu on GameStudio Editor.
HIDDEN_EDITOR_TYPES = ("SEQUENCE_EDITOR", "CLIP_EDITOR", "CompositorNodeTree")
_policy_tries = 0
_saved_statusbar_version = None


def _apply_editor_policy(hidden=HIDDEN_EDITOR_TYPES):
    """Fork-only polish via host (also a timer: the extension loads after us): hide editor types,
    and Blender's version from the status bar, where it reads like GameStudio's own."""
    global _policy_tries, _saved_statusbar_version
    host = gs_part("host")
    if host is None:
        _policy_tries += 1
        return 0.5 if _policy_tries < 40 else None
    if host.has("editor_type_filter"):
        host.editors.set_hidden_editor_types(hidden)
    view = bpy.context.preferences.view
    if hidden and host.is_editor_build() and _saved_statusbar_version is None:
        _saved_statusbar_version = view.show_statusbar_version
        view.show_statusbar_version = False
    elif not hidden and _saved_statusbar_version is not None:
        view.show_statusbar_version = _saved_statusbar_version
        _saved_statusbar_version = None
    return None


# --- Opening scenes keeps the IDE layout ------------------------------------------------

# Like other game engines, opening a scene does not replace the IDE's workspaces with the ones
# stored in the .blend. App templates cannot ship this setting in userpref.blend (Blender only
# takes themes, add-ons and keymaps from it), so it is applied here and restored on unregister.
_saved_load_ui = None


def _keep_ide_layout(enable):
    global _saved_load_ui
    filepaths = bpy.context.preferences.filepaths
    if enable:
        _saved_load_ui = filepaths.use_load_ui
        filepaths.use_load_ui = False
    elif _saved_load_ui is not None:
        filepaths.use_load_ui = _saved_load_ui
        _saved_load_ui = None


# --- Game layouts: GameStudio editors in the workspaces ---------------------------------

# startup.blend holds stock editors only, so it opens the same on stock Blender (which would turn
# an unknown editor into a 3D Viewport). build_template.py stores in each workspace, under
# LAYOUT_PROP, what to change per area, keyed by area type (the largest area of that type) or
# "TYPE/display_mode" (e.g. "OUTLINER/LIBRARIES"):
#   {"PROPERTIES": {"editor": "GAMESTUDIO_INSPECTOR"},
#    "DOPESHEET_EDITOR": {"editor": "GAMESTUDIO_CONSOLE", "height": 0.27},
#    "VIEW_3D": {"sidebar": "Game", "fork_sidebar": False}}
#   editor        GameStudio Editor: switch the area to this editor
#   height        ... and make it about this fraction of the window height, taken from the
#                 3D Viewport above it (the strip is closed into a fresh split of the viewport)
#   close         GameStudio Editor: close the area; its neighbor takes the space
#   sidebar       both hosts: the sidebar tab to show
#   fork_sidebar  GameStudio Editor: show the sidebar or not
# Blender only changes the editors of a screen a window shows, so each workspace is set up the
# first time it is shown; its entry is then removed, and the user's later changes are kept.
LAYOUT_PROP = "gamestudio_layout"
FORK_KEYS = ("editor", "height", "close", "fork_sidebar")
_LAYOUT_RETRIES = 30
_layout_tries = {}
_msgbus_owner = object()


def _largest(screen, key):
    """The largest area matching `key`: an area type, or "TYPE/display_mode"."""
    area_type, _, mode = key.partition("/")
    areas = [a for a in screen.areas if a.type == area_type
             and (not mode or getattr(a.spaces.active, "display_mode", None) == mode)]
    return max(areas, key=lambda a: a.width * a.height) if areas else None


def _host():
    host = gs_part("host")
    return host if host is not None and hasattr(host, "editors") else None


def _editor_ready(host, idname) -> bool:
    if idname == getattr(host.game_view, "IDNAME", None):
        return host.game_view.available()
    return host.editors.is_registered(idname)


def _applicable(slot: dict, fork: bool) -> dict:
    return {k: v for k, v in slot.items() if fork or k not in FORK_KEYS}


def layout_pending(workspace, fork: bool) -> bool:
    spec = workspace.get(LAYOUT_PROP)
    if not spec:
        return False
    return any(_applicable(slot.to_dict(), fork) for slot in spec.values())


def _set_sidebar_tab(area, tab) -> bool:
    for region in area.regions:
        if region.type == "UI":
            try:
                region.active_panel_category = tab
            except (AttributeError, TypeError, ValueError):
                return False  # the sidebar has not drawn its tabs yet
            return region.active_panel_category == tab
    return True  # no sidebar: nothing to do


def _split_below(window, view3d, height_px):
    """Split a new area of about `height_px` off the bottom of a 3D Viewport; return it, or None."""
    screen = window.screen
    before = {a.as_pointer() for a in screen.areas}
    factor = min(0.45, max(0.1, height_px / max(1, view3d.height)))
    with bpy.context.temp_override(window=window, screen=screen, area=view3d):
        if "FINISHED" not in bpy.ops.screen.area_split(direction="HORIZONTAL", factor=factor):
            return None
    return next((a for a in screen.areas if a.as_pointer() not in before), None)


def _close_area(window, area) -> bool:
    with bpy.context.temp_override(window=window, screen=window.screen, area=area):
        return "FINISHED" in bpy.ops.screen.area_close()


def _place_editor(window, area, idname, height):
    """Switch `area` to `idname`. With `height`, a strip under the 3D Viewport (the Timeline is
    too short for a console) is traded for a split of the viewport of about that size."""
    above = _largest(window.screen, "VIEW_3D")
    want = int(height * window.height) - area.height if height else 0
    stacked = above is not None and abs(above.x - area.x) < 4 and abs(above.width - area.width) < 4 \
        and abs(above.y - (area.y + area.height)) < 8
    if want > 40 and stacked:
        new = _split_below(window, above, want)
        if new is not None:
            new.ui_type = idname
            _close_area(window, area)  # the strip joins the new editor above it
            return
    area.ui_type = idname


def _apply_slot(window, host, area, todo: dict) -> dict:
    """Apply one area's steps; return the steps to retry later."""
    left = {}
    if "sidebar" in todo and not _set_sidebar_tab(area, todo["sidebar"]):
        left["sidebar"] = todo["sidebar"]
    if "fork_sidebar" in todo:
        if left:
            left["fork_sidebar"] = todo["fork_sidebar"]  # hide it once its tab is set
        else:
            area.spaces.active.show_region_ui = bool(todo["fork_sidebar"])
    if todo.get("close"):
        _close_area(window, area)
        return left
    if "editor" in todo:
        if not _editor_ready(host, todo["editor"]):
            left.update({k: todo[k] for k in ("editor", "height") if k in todo})
        else:
            try:
                _place_editor(window, area, todo["editor"], todo.get("height"))
            except (RuntimeError, TypeError, ValueError) as exc:
                print(f"GameStudio: could not open {todo['editor']} in '{window.workspace.name}': {exc}")
    return left


def _apply_layout(window, host) -> bool:
    """Set up the workspace `window` shows. Returns True when nothing is left to retry."""
    workspace = window.workspace
    spec = workspace.get(LAYOUT_PROP)
    if not spec:
        return True
    fork = host.has("extension_editors")
    remaining = {}
    # Steps that resize go last: they close an area.
    for area_type, slot in sorted(spec.to_dict().items(), key=lambda item: "height" in item[1] or "close" in item[1]):
        todo = _applicable(slot, fork)
        left = {k: v for k, v in slot.items() if k not in todo}  # fork-only steps, kept on stock
        area = _largest(window.screen, area_type)
        if area is None:
            continue  # the user already changed this layout
        if todo:
            left.update(_apply_slot(window, host, area, todo))
        if left:
            remaining[area_type] = left
    tries = _layout_tries[workspace.name] = _layout_tries.get(workspace.name, 0) + 1
    retry = any(_applicable(slot, fork) for slot in remaining.values())
    if retry and tries < _LAYOUT_RETRIES:
        workspace[LAYOUT_PROP] = remaining
        return False
    kept = {t: {k: v for k, v in slot.items() if k in FORK_KEYS} for t, slot in remaining.items()} if not fork else {}
    kept = {t: slot for t, slot in kept.items() if slot}
    if kept:
        workspace[LAYOUT_PROP] = kept
    else:
        del workspace[LAYOUT_PROP]
    return True


def _layout_tick():
    """Set up the workspaces windows show; poll while any workspace still needs it."""
    host = _host()
    wm = bpy.context.window_manager
    if host is None or wm is None or not wm.windows:
        return 0.25
    fork = host.has("extension_editors")
    for window in wm.windows:
        if window.screen is not None and not getattr(window.screen, "is_temporary", False):
            _apply_layout(window, host)
    if any(layout_pending(ws, fork) for ws in bpy.data.workspaces):
        return 0.5
    return None


def _schedule_layout(delay=0.0):
    if bpy.app.timers.is_registered(_layout_tick):
        bpy.app.timers.unregister(_layout_tick)
    bpy.app.timers.register(_layout_tick, first_interval=delay, persistent=True)


def _on_workspace_changed(*_args):
    _schedule_layout()


def _subscribe_workspace_changes():
    """Set up a workspace right when its tab is clicked (the 0.5 s poll covers Ctrl+PageUp)."""
    bpy.msgbus.clear_by_owner(_msgbus_owner)
    try:
        bpy.msgbus.subscribe_rna(key=(bpy.types.Window, "workspace"), owner=_msgbus_owner, args=(),
                                 notify=_on_workspace_changed)
    except (TypeError, ValueError, KeyError):
        pass


@persistent
def _on_load_post(*_args):
    _layout_tries.clear()
    _subscribe_workspace_changes()
    _schedule_layout()


# --- Registration ----------------------------------------------------------------------

_REPLACED = [
    (TOPBAR_MT_editor_menus, upstream_topbar.TOPBAR_MT_editor_menus),
    (TOPBAR_HT_upper_bar, upstream_topbar.TOPBAR_HT_upper_bar),
    (WM_MT_splash, upstream_wm.WM_MT_splash),
    (WM_MT_splash_about, upstream_wm.WM_MT_splash_about),
    (WM_MT_splash_quick_setup, upstream_wm.WM_MT_splash_quick_setup),
]
_NEW = (GAMESTUDIO_MT_app, GAMESTUDIO_MT_game, GAMESTUDIO_MT_help, GAMESTUDIO_OT_first_run_done)


def register():
    for cls in _NEW:
        bpy.utils.register_class(cls)
    for ours, upstream in _REPLACED:
        # Unregister the upstream class explicitly. Relying on Blender's implicit
        # "registered before, unregistering previous" leaves bpy.types pointing at a
        # stale type when a subclass replaces its own base on a re-register
        # (template switch). blender/tests/shell catches this.
        if upstream.is_registered:
            bpy.utils.unregister_class(upstream)
        bpy.utils.register_class(ours)
    bpy.types.TOPBAR_MT_file.prepend(_file_menu_projects)
    _keep_ide_layout(True)
    global _policy_tries
    _policy_tries = 0
    if _apply_editor_policy() is not None and not bpy.app.timers.is_registered(_apply_editor_policy):
        bpy.app.timers.register(_apply_editor_policy, first_interval=0.5, persistent=True)
    if _on_load_post not in bpy.app.handlers.load_post:
        bpy.app.handlers.load_post.append(_on_load_post)
    _subscribe_workspace_changes()
    _schedule_layout(0.1)


def unregister():
    bpy.msgbus.clear_by_owner(_msgbus_owner)
    if _on_load_post in bpy.app.handlers.load_post:
        bpy.app.handlers.load_post.remove(_on_load_post)
    if bpy.app.timers.is_registered(_layout_tick):
        bpy.app.timers.unregister(_layout_tick)
    if bpy.app.timers.is_registered(_apply_editor_policy):
        bpy.app.timers.unregister(_apply_editor_policy)
    _apply_editor_policy(hidden=())  # give the user back every editor type
    _keep_ide_layout(False)
    bpy.types.TOPBAR_MT_file.remove(_file_menu_projects)
    for ours, upstream in reversed(_REPLACED):
        if ours.is_registered:
            bpy.utils.unregister_class(ours)
        if not upstream.is_registered:
            bpy.utils.register_class(upstream)  # give the user back stock Blender
    for cls in reversed(_NEW):
        bpy.utils.unregister_class(cls)

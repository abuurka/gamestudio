"""GameStudio: the app template that turns Blender into the GameStudio IDE.

This is layer L3 in docs/fork/ARCHITECTURE.md. It only *overrides* Blender's
Python-defined UI and never edits upstream files. In order of preference it:
  1. appends to menus;
  2. subclasses an upstream class and calls the original draw;
  3. replaces a class outright (only for the top bar menus, the splash and About).
Every replaced class is restored on unregister.

The template's startup.blend (workspaces) and userpref.blend (theme, enabled
extensions, keymap tweaks) are generated by editor/shell/tools/build_template.py.

Game features come from the GameStudio extension, which is enabled by the
template's userpref.blend. The template registers before extensions are loaded,
so it looks the extension up lazily, at draw time.
"""


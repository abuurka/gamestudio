RECENT_ROWS = 4


def gs():
    """The GameStudio extension module, whatever name it was loaded under, or None."""
    for name in bpy.context.preferences.addons.keys():
        if name == "gamestudio" or name.endswith(".gamestudio"):
            try:
                return importlib.import_module(name)
            except ImportError:
                return None
    return None


def gs_part(attr):
    module = gs()
    if module is None:
        return None
    try:
        return importlib.import_module(f"{module.__name__}.{attr}")
    except ImportError:
        return None


def _muted(layout):
    row = layout.row()
    row.active = False
    return row



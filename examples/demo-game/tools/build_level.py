"""Builds examples/demo-game/scenes/main.blend: the "Coin Courtyard" demo level.

The level is generated by a script so it can be rebuilt at any time. It uses the
GameStudio add-on's own API to attach components, the same way the Game panel
does.

Run from the repository root (after `npm install` and `npm run registry -w demo-game`):

  blender --background --factory-startup --python examples/demo-game/tools/build_level.py
"""

import math
import pathlib
import sys

import bpy
from mathutils import Vector

PROJECT = pathlib.Path(__file__).resolve().parents[1]
REPO = PROJECT.parents[1]
sys.path.insert(0, str(REPO / "blender"))

import gamestudio  # noqa: E402
from gamestudio.core import components, export, registry  # noqa: E402

bpy.ops.wm.read_factory_settings(use_empty=True)
gamestudio.register()
if not registry.reload_registry(PROJECT):
    raise SystemExit("No component registry found. Run `npm run registry -w demo-game` first.")

scene = bpy.context.scene
scene.name = "main"
# The game tone-maps as the scene's Color Management says: change the exposure here, not in code.
scene.view_settings.view_transform, scene.view_settings.look = "Khronos PBR Neutral", "None"
SKY = (0.38, 0.55, 0.78)
world = bpy.data.worlds.new("Sky")
world.color = SKY
if world.node_tree and "Background" in world.node_tree.nodes:
    # New worlds get a Background node, and its color wins over world.color.
    world.node_tree.nodes["Background"].inputs["Color"].default_value = (*SKY, 1.0)
scene.world = world

_materials: dict[str, bpy.types.Material] = {}


def material(name, rgba, roughness=0.6, metallic=0.0):
    if name in _materials:
        return _materials[name]
    mat = bpy.data.materials.new(name)
    mat.diffuse_color = rgba
    bsdf = mat.node_tree.nodes.get("Principled BSDF") if mat.node_tree else None
    if bsdf:
        bsdf.inputs["Base Color"].default_value = rgba
        bsdf.inputs["Roughness"].default_value = roughness
        bsdf.inputs["Metallic"].default_value = metallic
    _materials[name] = mat
    return mat


def collection(name):
    coll = bpy.data.collections.new(name)
    scene.collection.children.link(coll)
    return coll


def link(obj, coll):
    for other in list(obj.users_collection):
        other.objects.unlink(obj)
    coll.objects.link(obj)


def box(name, coll, location, size, mat, rotation_deg=(0, 0, 0)):
    bpy.ops.mesh.primitive_cube_add(size=1, location=location)
    obj = bpy.context.object
    obj.name = name
    obj.scale = size
    obj.rotation_euler = [math.radians(a) for a in rotation_deg]
    obj.data.materials.append(mat)
    link(obj, coll)
    return obj


def cylinder(name, coll, location, radius, depth, mat, rotation_deg=(0, 0, 0)):
    bpy.ops.mesh.primitive_cylinder_add(radius=radius, depth=depth, vertices=32, location=location)
    obj = bpy.context.object
    obj.name = name
    obj.rotation_euler = [math.radians(a) for a in rotation_deg]
    obj.data.materials.append(mat)
    bpy.ops.object.shade_smooth()
    link(obj, coll)
    return obj


GRASS = material("Grass", (0.22, 0.45, 0.2, 1))
STONE = material("Stone", (0.55, 0.55, 0.6, 1))
WOOD = material("Wood", (0.72, 0.45, 0.2, 1))
GOLD = material("Gold", (1.0, 0.75, 0.1, 1), roughness=0.25, metallic=1.0)
PLAYER = material("PlayerBlue", (0.15, 0.35, 0.95, 1))
PAD = material("BounceMagenta", (0.9, 0.2, 0.75, 1))
LAVA = material("Lava", (1.0, 0.18, 0.02, 1), roughness=0.3)
CRYSTAL = material("Crystal", (0.3, 0.95, 0.9, 1), roughness=0.1)

level = collection("Level")
props = collection("Props")
pickups = collection("Pickups")
actors = collection("Actors")

# --- Static level geometry (a Collider with no RigidBody is fixed) -------------
ground = box("Ground", level, (0, 0, -0.25), (30, 30, 0.5), GRASS)
components.add_component(ground, "Collider")

platform = box("Platform", level, (9, -6, 1.5), (5, 5, 0.5), STONE)
components.add_component(platform, "Collider")
ramp = box("Ramp", level, (9, -1.2, 0.85), (3, 5.2, 0.3), STONE, rotation_deg=(-17, 0, 0))
components.add_component(ramp, "Collider")

ledge = box("HighLedge", level, (-7, 8, 4.0), (4, 3, 0.4), STONE)
components.add_component(ledge, "Collider")

for i, (x, y, sx, sy) in enumerate([(0, 15.25, 30.5, 0.5), (0, -15.25, 30.5, 0.5),
                                    (15.25, 0, 0.5, 30), (-15.25, 0, 0.5, 30)]):
    wall = box(f"Wall{i + 1}", level, (x, y, 0.5), (sx, sy, 1.0), STONE)
    components.add_component(wall, "Collider")

# --- Hazards and gameplay pieces --------------------------------------------------
lava = box("LavaStrip", level, (0, 7, 0.03), (12, 2, 0.06), LAVA)
components.add_component(lava, "KillZone")

pad = cylinder("BouncePad", props, (-7, 4.5, 0.1), 1.0, 0.2, PAD)
components.add_component(pad, "BouncePad", {"strength": 14})
components.add_component(pad, "Collider")

for i, (x, y, z) in enumerate([(4, 4, 0.5), (4, 4, 1.5), (5.1, 4, 0.5), (4.5, 4, 2.5)]):
    crate = box(f"Crate{i + 1}", props, (x, y, z), (1, 1, 1), WOOD, rotation_deg=(0, 0, 7 * i))
    components.add_component(crate, "RigidBody", {"type": "dynamic", "mass": 2})
    components.add_component(crate, "Collider", {"friction": 0.7})

crystal = box("Crystal", props, (-4, -4, 3.2), (0.6, 0.6, 0.6), CRYSTAL, rotation_deg=(45, 35, 0))
components.add_component(crystal, "Spin", {"speed": 1.5, "axis": [0.3, 1, 0.2]})

coin_spots = [
    (3, -3, 1.0),      # in the open
    (-3, -3, 1.0),
    (9, -6, 2.75),     # on the platform, up the ramp
    (-7, 8.5, 5.2),    # on the high ledge: use the bounce pad
    (0, 10, 1.0),      # past the lava strip: jump it
    (4.5, 2.5, 1.0),   # by the crates
]
for i, loc in enumerate(coin_spots):
    coin = cylinder(f"Coin{i + 1}", pickups, loc, 0.35, 0.08, GOLD, rotation_deg=(90, 0, 0))
    components.add_component(coin, "Coin", {"value": 1})

# --- Player, spawn, camera, light --------------------------------------------------
player = cylinder("Player", actors, (0, -9, 0.95), 0.4, 1.8, PLAYER)
components.add_component(player, "RigidBody", {"type": "kinematic"})
components.add_component(player, "Collider", {"shape": "capsule"})
components.add_component(player, "CharacterController", {"speed": 6, "jumpSpeed": 7})

start = bpy.data.objects.new("PlayerStart", None)
start.empty_display_type = "ARROWS"
start.location = (0, -9, 0)
actors.objects.link(start)
components.add_component(start, "PlayerStart")

cam = bpy.data.objects.new("Camera", bpy.data.cameras.new("Camera"))
cam.data.lens = 24  # a wide lens suits a third-person game; Blender's 50 mm default is telephoto
actors.objects.link(cam)
cam.location = (0, -17, 5)
cam.rotation_euler = (Vector((0, -9, 1)) - cam.location).to_track_quat("-Z", "Y").to_euler()
scene.camera = cam
components.add_component(cam, "FollowCamera", {"target": "Player", "offset": [0, 4, 8],
                                                "smoothing": 5, "lookAtOffset": [0, 1, 0]})

sun = bpy.data.objects.new("Sun", bpy.data.lights.new("Sun", type="SUN"))
sun.data.energy = 4.0
sun.rotation_euler = (math.radians(45), math.radians(20), math.radians(35))
actors.objects.link(sun)

# --- Save and export -------------------------------------------------------------
def forget_file_browser_folders():
    """Blender opens the Shading workspace's File Browser in this computer's Documents folder,
    and the shipped file must not carry that path. Assigning a path only moves the string's end
    (the rest of the old one stays in the buffer), so shorten it a byte at a time down to "//",
    the folder of the .blend: that clears the whole buffer."""
    for screen in bpy.data.screens:
        for area in screen.areas:
            for space in area.spaces:
                params = space.params if space.type == "FILE_BROWSER" else None
                if params is not None:
                    params.directory = b"/" * 4096  # Blender cuts it to the buffer's length
                    for n in range(len(params.directory), 1, -1):
                        params.directory = b"/" * n


forget_file_browser_folders()
blend = PROJECT / "scenes" / "main.blend"
blend.parent.mkdir(exist_ok=True)
bpy.ops.wm.save_as_mainfile(filepath=str(blend))
result = export.export_scene(scene)
bpy.ops.wm.save_mainfile()  # keep the IDs and export revision assigned during export
print("LEVEL_OK", blend, result)
